import { afterEach, expect, it, vi } from 'vitest';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../src/app.ts';
let dir:string;
afterEach(()=>{vi.unstubAllEnvs();if(dir)rmSync(dir,{recursive:true,force:true});});
it('uses the configured public URL for invite and share links while preserving JSON contracts', async()=>{
  vi.stubEnv('CAIRN_PUBLIC_URL','https://notes.example.com/');
  dir=mkdtempSync(join(tmpdir(),'cairn-links-'));
  const app=createApp({dataDir:dir});
  let cookie='';
  const api=(path:string,method='GET',body?:unknown)=>app.request(path,{method,headers:{Cookie:cookie,'X-Cairn-Client':'link-test','Content-Type':'application/json'},...(body===undefined?{}:{body:JSON.stringify(body)})});
  const signup=await api('/api/auth/signup','POST',{email:'owner@example.com',name:'Owner',password:'password123'});
  cookie=signup.headers.get('set-cookie')!.split(';')[0];
  const wid=(await signup.json() as any).workspaces[0].id;
  const invitation=await api(`/api/workspaces/${wid}/invites`,'POST',{role:'member'});
  const invite=await invitation.json() as any;
  expect(invitation.headers.get('link')).toBe(`<https://notes.example.com/invite/${invite.token}>; rel="canonical"`);
  const p=await (await api(`/api/workspaces/${wid}/pages`,'POST',{title:'Safe search',content:{type:'doc',content:[{type:'paragraph',content:[{type:'text',text:'Needle <script> & text'}]}]}})).json() as any;
  const shared=await api(`/api/pages/${p.id}/share`,'POST');
  const token=await shared.json() as any;
  expect(Object.keys(token)).toEqual(['token']);
  expect(shared.headers.get('link')).toContain(`https://notes.example.com/s/${token.token}`);
  const hits=await (await api(`/api/workspaces/${wid}/search?q=needle`)).json() as any[];
  expect(hits[0].snippet).toContain('<mark>Needle</mark>');
  expect(hits[0].snippet).toContain('&lt;script&gt; &amp; text');
  expect(hits[0].snippet).not.toContain('<script>');
});
